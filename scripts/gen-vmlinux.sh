#!/usr/bin/env bash
# Regenerates internal/tracer/bpf/include/vmlinux.h, the kernel types the BPF
# programs include, with bpftool from the BTF of the running kernel or of the
# given file (raw BTF or vmlinux ELF), and records that kernel in a comment
# at the top. Compile the programs again afterwards (make generate) and
# check them (make compat, make test-root).
#
#   scripts/gen-vmlinux.sh [BTF file] [output file]
#
# KERNEL describes the kernel of a BTF file, e.g. KERNEL="Rocky Linux 9.6
# 5.14.0-570.58.1.el9_6.x86_64"; the default is the name of the file.
# BPFTOOL is the bpftool to use.
set -euo pipefail

btf="${1:-/sys/kernel/btf/vmlinux}"
out="${2:-$(dirname "$0")/../internal/tracer/bpf/include/vmlinux.h}"
bpftool="${BPFTOOL:-bpftool}"

if [[ -z "${KERNEL:-}" ]]; then
	if [[ "$btf" == /sys/kernel/btf/vmlinux ]]; then
		KERNEL="Linux $(uname -r) $(uname -m)"
	else
		KERNEL="$(basename "$btf")"
	fi
fi
tool="$("$bpftool" version | sed -n 1p)"

tmp="$(mktemp "$out.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
	echo "/* Generated by scripts/gen-vmlinux.sh with $tool from the BTF of"
	echo " * $KERNEL. Do not edit. See NOTICE for the license. */"
	"$bpftool" btf dump file "$btf" format c
} >"$tmp"
chmod 0644 "$tmp"
mv "$tmp" "$out"
trap - EXIT
echo "wrote $out from the BTF of $KERNEL"
